#!/usr/bin/env node
/**
 * Keeps the product list in public/llms.txt equal to the catalogue. Everything between the two PRODUCTS markers
 * is generated from content/products.ts (English name, Hindi name, short description, English and Hindi URLs);
 * the rest of the file is hand-written and untouched.
 *
 *   node scripts/build-llms.mjs            rewrite the block
 *   node scripts/build-llms.mjs --check    exit 1 if the block is out of date
 *
 * Runs before `npm run build` (see "prebuild").
 */
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const root = path.resolve(import.meta.dirname, "..");
const file = path.join(root, "public", "llms.txt");
const imp = (p) => import(pathToFileURL(path.join(root, p)).href);
const { allProducts, categories } = await imp("content/products.ts");
const { catalogHi } = await imp("content/hi/catalog.ts");
const BASE = "https://www.hmibrahim.net";
const START = "<!-- PRODUCTS:START (generated by scripts/build-llms.mjs, do not edit by hand) -->";
const END = "<!-- PRODUCTS:END -->";

const hi = (s) => catalogHi[s] || "";
const lines = [
  START,
  "## Every product the shop sells (English and Hindi pages)",
  "",
  "Sold retail (single pieces, cut lengths, small quantities) and wholesale or in bulk to shop owners, traders, dealers and contractors. Send the size and quantity to get a rate; prices are not listed on the website. Each product has an English page and a Hindi page.",
  "",
];
for (const c of categories) {
  const items = allProducts.filter((p) => p.categorySlug === c.slug);
  if (!items.length) continue;
  lines.push(`### ${c.name}${hi(c.name) ? ` (${hi(c.name)})` : ""}`, "");
  for (const p of items) {
    const h = hi(p.name);
    const desc = (p.shortDesc || "").replace(/\s+/g, " ").trim();
    lines.push(
      `- [${p.name}](${BASE}/products/${p.slug})${h ? ` / [${h}](${BASE}/hi/products/${p.slug})` : ` / [Hindi page](${BASE}/hi/products/${p.slug})`}${desc ? `: ${desc}` : ""}`
    );
  }
  lines.push("");
}
lines.push(END);
const block = lines.join("\n");

let text = fs.readFileSync(file, "utf8");
let next;
if (text.includes(START) && text.includes(END)) {
  next = text.slice(0, text.indexOf(START)) + block + text.slice(text.indexOf(END) + END.length);
} else {
  const at = text.indexOf("## Key pages");
  next = text.slice(0, at) + block + "\n\n" + text.slice(at);
}
if (process.argv.includes("--check")) {
  if (next !== text) {
    console.error("public/llms.txt product list is out of date: run node scripts/build-llms.mjs");
    process.exit(1);
  }
  console.log("llms.txt product list is current");
} else {
  fs.writeFileSync(file, next);
  console.log(`llms.txt: ${allProducts.length} products written`);
}
